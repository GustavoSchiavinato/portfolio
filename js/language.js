let currentLanguage = "pt";


/* =========================================================
   APLICAR TRADUÇÃO
   ========================================================= */

function applyLanguage(language) {

    if (!translations[language]) {
        return;
    }


    currentLanguage = language;


    /*
     * Procura todos os elementos que possuem
     * data-i18n no HTML.
     */

    const elements =
        document.querySelectorAll("[data-i18n]");


    elements.forEach(element => {

        const key =
            element.getAttribute("data-i18n");


        if (
            translations[language][key] !== undefined
        ) {

            element.textContent =
                translations[language][key];

        }

    });


    /* =====================================================
       ATUALIZA BOTÕES DE IDIOMA
    ===================================================== */

    const languageButtons =
        document.querySelectorAll(
            ".language-button"
        );


    languageButtons.forEach(button => {

        const buttonLanguage =
            button.getAttribute("data-lang");


        button.classList.toggle(
            "active",
            buttonLanguage === language
        );

    });


    /* =====================================================
       ATUALIZA O ATRIBUTO LANG DO HTML
    ===================================================== */

    document.documentElement.lang =
        language === "pt"
            ? "pt-BR"
            : language;


    /*
     * Guarda o idioma escolhido.
     * Assim, se a página for atualizada,
     * podemos recuperar a escolha.
     */

    localStorage.setItem(
        "portfolioLanguage",
        language
    );

}


/* =========================================================
   EVENTOS DOS BOTÕES
   ========================================================= */

function setupLanguageSelector() {

    const languageButtons =
        document.querySelectorAll(
            ".language-button"
        );


    languageButtons.forEach(button => {

        button.addEventListener(
            "click",
            () => {

                const language =
                    button.getAttribute("data-lang");


                applyLanguage(language);

            }
        );

    });

}


/* =========================================================
   INICIALIZAÇÃO
   ========================================================= */

document.addEventListener(
    "DOMContentLoaded",
    () => {

        setupLanguageSelector();


        /*
         * Recupera o idioma salvo.
         * Se não existir, usa português.
         */

        const savedLanguage =
            localStorage.getItem(
                "portfolioLanguage"
            );


        if (
            savedLanguage &&
            translations[savedLanguage]
        ) {

            applyLanguage(savedLanguage);

        } else {

            applyLanguage("pt");

        }

    }
);
